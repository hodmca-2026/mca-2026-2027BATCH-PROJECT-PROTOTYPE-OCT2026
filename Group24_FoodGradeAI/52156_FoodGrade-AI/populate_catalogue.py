def populate():
    conn = sqlite3.connect(DB_PATH)
    conn.row_factory = sqlite3.Row

    # Clear products table and repopulate with all 20 genuine Indian products
    conn.execute("DELETE FROM products")
    conn.execute("DELETE FROM sqlite_sequence WHERE name='products'")

    for p in PRODUCTS_20:
        res = calculate_foodgrade(p)
        conn.execute(
            """
            INSERT INTO products (
                id, product_name, brand, category, barcode, ingredients, claims,
                calories, sugar, total_fat, saturated_fat, protein, fibre, salt,
                health_score, health_grade, claim_score, claim_grade, claim_status,
                source, source_url, image_url, data_quality_score
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                p["id"],
                p["product_name"],
                p["brand"],
                p["category"],
                p["barcode"],
                p["ingredients"],
                p["claims"],
                p["calories"],
                p["sugar"],
                p["total_fat"],
                p["saturated_fat"],
                p["protein"],
                p["fibre"],
                p["salt"],
                res["health_score"],
                res["health_grade"],
                res["claim_score"],
                res["claim_grade"],
                res["claim_status"],
                p.get("source", "Open Food Facts"),
                p.get("source_url", ""),
                p.get("image_url", ""),
                res.get("data_quality_score", 100.0),
            )
        )

    conn.commit()
    count = conn.execute("SELECT COUNT(*) FROM products").fetchone()[0]
    print(f"Successfully populated database with {count} Indian products!")

    # Verify categories
    cats = conn.execute("SELECT DISTINCT category FROM products ORDER BY category").fetchall()
    print("Categories present:", [c[0] for c in cats])

    conn.close()


if __name__ == "__main__":
    populate()
